/** Package the browser engine and binary scene assets for restricted PHP hosts.
 * Each generated PHP source chunk stays below 400 KiB. The endpoint decodes
 * the original bytes; nothing is executed/transcoded/rendered server-side.
 */
import fs from 'node:fs';
import crypto from 'node:crypto';
const entries={
 engine:['assets/vendor/story-3d.js','application/javascript; charset=utf-8'],
 'basis-wasm':['assets/reference/vendor/basis/basis_transcoder.wasm','application/wasm'],
 'draco-wasm':['assets/reference/vendor/draco/draco_decoder.wasm','application/wasm'],
 'hand-atlas':['assets/reference/assets/atlases/human_hands.ktx2','image/ktx2'],
 'texts-atlas':['assets/reference/assets/atlases/texts.ktx2','image/ktx2'],
 'money-atlas':['assets/reference/assets/atlases/leather-money-shreds.ktx2','image/ktx2'],
 'hand-model':['assets/reference/assets/models/human_hand_2.glb','model/gltf-binary'],
 'camera-model':['assets/reference/assets/models/camera_2.glb','model/gltf-binary'],
 'fracture-model':['assets/reference/assets/models/stage2_glass-shatter.glb','model/gltf-binary'],
 'shard-model':['assets/reference/assets/models/glass_shards.glb','model/gltf-binary'],
 'tunnel-model':['assets/reference/assets/models/tunnel_new_new.glb','model/gltf-binary']
};
const dir='app/scene-payloads';fs.mkdirSync(dir,{recursive:true});
const keep=new Set();let php="<?php\n/** Generated by tools/build-scene-assets.mjs; public-scene allowlist only. */\nreturn [\n";
for(const [id,[file,type]] of Object.entries(entries)){
 const bytes=fs.readFileSync(file),chunks=[];
 for(let offset=0,n=0;offset<bytes.length;offset+=256*1024,n++){
  const name=`${id}-${n}.php`;keep.add(name);chunks.push(name);
  fs.writeFileSync(`${dir}/${name}`,`<?php\n/* Generated public asset payload, not executable application code. */\nreturn '${bytes.subarray(offset,offset+256*1024).toString('base64')}';\n`);
 }
 php+=` '${id}'=>['path'=>'${file}','type'=>'${type}','bytes'=>${bytes.length},'sha256'=>'${crypto.createHash('sha256').update(bytes).digest('hex')}','chunks'=>[${chunks.map(n=>`'${n}'`).join(',')}]],\n`;
}
for(const name of fs.readdirSync(dir))if(/^[a-z-]+-\d+\.php$/.test(name)&&!keep.has(name))fs.unlinkSync(`${dir}/${name}`);
fs.writeFileSync('app/scene-manifest.php',php+'];\n');
console.log(`Packaged ${Object.keys(entries).length} public scene assets in ${keep.size} bounded PHP payloads.`);
